CLR = {"ink": "black", "dim": "black!55", "steel": "steelc", "port": "portc", "stb": "stbc", "brass": "brassc", "rule": "black!25"}


def rect(x, y, w, h, fill, op=1.0, stroke=None):
    """A rectangle with top-left corner (x, y) in cm, y growing upward."""
    f = f"fill={CLR.get(fill, fill)}, fill opacity={op}" if fill else ""
    s = f"draw={CLR.get(stroke, stroke)}, line width=0.4pt" if stroke else "draw=none"
    return f"\\path[{', '.join(p for p in (f, s) if p)}] ({x:.3f},{y - h:.3f}) rectangle ({x + w:.3f},{y:.3f});\n"


def text(x, y, s, size="scriptsize", anchor="west", color="ink", bold=False):
    b = "\\bfseries " if bold else ""
    return f"\\node[anchor={anchor}, inner sep=0pt, text={CLR.get(color, color)}, font=\\{size}] at ({x:.3f},{y:.3f}) {{{b}{s}}};\n"


def fig_weight():
    bw, dense = 12.0, 0.04
    o = "\\begin{tikzpicture}\n" + text(0, 0.3, "ONE LAYER", bold=True)
    o += rect(0, 0, bw * dense, 0.7, "ink")
    ex0, exw, n = bw * dense + 0.05, bw - bw * dense - 0.05, 32
    cw = exw / n
    for i in range(n):
        o += rect(ex0 + i * cw + 0.01, 0, cw - 0.02, 0.7, "steel", 1.0 if i in (3, 9, 17, 26) else 0.35)
    o += text(0, -0.95, "dense part", color="ink") + text(0, -1.3, "attention, router", color="dim")
    o += text(ex0 + exw, -0.95, "experts: about 96\\% of the weights", anchor="east") + text(ex0 + exw, -1.3, "bright = the few a token uses", anchor="east", color="dim")
    o += text(0, -2.2, "KV CACHE (attention memory)", bold=True)
    for i, (f, lab) in enumerate([(0.18, "short chat"), (0.42, "long document"), (0.78, "very long context")]):
        y = -2.5 - i * 0.4
        o += rect(0, y, bw * f, 0.25, "ink", 0.55) + text(bw * f + 0.15, y - 0.125, lab, color="dim")
    o += text(0, -4.25, "Both stay on the main card. Only the experts are spread out.")
    return o + "\\end{tikzpicture}\n"


