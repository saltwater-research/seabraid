def fig_racks():
    """The placement pyramid for one layer (layer 3): cards in rung order, then the engine's own RAM and NVMe tiers."""
    step, hgt, w0, dw, cw = 1.85, 1.3, 3.6, 1.8, 0.85
    o, ym, cell = "\\begin{tikzpicture}\n", [], {}
    for i, (name, c, cells) in enumerate(LEVELS):
        w, y = w0 + dw * i, -i * step
        ym.append(y - hgt / 2)
        o += rect(-w / 2, y, w, hgt, c, 0.15, "ink") + text(-w / 2 + 0.12, y - 0.25, name, size="tiny", color=c, bold=True)
        for j, (lab, st) in enumerate(cells):
            x = w / 2 - 0.12 - cw - j * (cw + 0.08)
            o += rect(x, y - 0.55, cw, 0.5, c, {"hot": 1.0, "cold": 0.45, "mid": 0.45}.get(st, 0.3), "ink" if st else None)
            o += text(x + cw / 2, y - 0.8, lab, anchor="center", size="tiny")
            cell[(i, lab)] = (x + cw / 2, y - 0.55, y - 1.05)
    for (lo, a), (hi, b), n in (((2, "E9"), (1, "E2"), "1"), ((1, "E2"), (0, "E5"), "2")):  # swap n: hot cell below trades with the cell above
        (xl, yl, _), (xh, _, yh) = cell[(lo, a)], cell[(hi, b)]
        o += f"\\draw[{{Stealth}}-{{Stealth}}, line width=0.9pt] ({xl:.3f},{yl:.3f}) -- ({xh:.3f},{yh:.3f});\n"
        o += text((xl + xh) / 2 + 0.2, (yl + yh) / 2, f"swap {n}" + (" (later)" if n == "2" else ""), size="tiny", bold=True)
    xr = 6.3
    for i in (3, 4):
        o += f"\\draw[dashed, line width=0.6pt, black!60] ({(w0 + dw * i) / 2:.3f},{ym[i]:.3f}) -- ({xr:.3f},{ym[i]:.3f});\n"
    o += f"\\draw[dashed, -{{Stealth}}, line width=0.6pt, black!60] ({xr:.3f},{ym[4]:.3f}) -- ({xr:.3f},{ym[0]:.3f}) -- ({(w0) / 2:.3f},{ym[0]:.3f});\n"
    o += f"\\node[anchor=west, inner sep=0pt, text width=2.4cm, font=\\tiny, text=black!70] at ({xr + 0.15:.3f},{(ym[0] + ym[2]) / 2:.3f}) {{engine cache (Strata): the engine moves experts between NVMe, RAM and the main card, not \\product}};\n"
    o += text(-w0 / 2 - 0.1, ym[0], "layer 3 shown", size="tiny", color="dim", anchor="east")
    return o + "\\end{tikzpicture}\n"


