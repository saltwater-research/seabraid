"""Generate the TikZ figures fig-weight.tex, fig-racks.tex and fig-archs.tex (plain primitives, no loops, no libraries).

OWNER: this file owns the drawing data of three paper figures (the system diagram fig-system.tex is hand-written).
WHY a generator: the archs figure is six panels of the same grid drawn from data; generating explicit \\path and
\\node lines keeps the .tex free of macro logic that cannot be tested without a TeX engine on the build box.
CONTRACT: ``python gen_figures.py [outdir]`` writes the three files next to this script by default; pure text out.
SIZE: under 200 lines.  FAILURE: an exception; nothing is written half-way (all text is built first).
Schematic only: the figures are labelled "not to scale" in the paper.
"""
