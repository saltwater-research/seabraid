LAYERS, W, U = 6, 320.0, 0.0215


def place_items(a, l, y, pad, colw):
    o = ""
    for j, items in enumerate(a["place"](l)):
        x = pad + j * colw + 3
        for it in items:
            if it in ("D", "d"):
                w = 16 if it == "D" else 8
                o += rect(x * U, -(y + 2) * U, w * U, 9 * U, "ink", 0.9)
                x += w + 3
                continue
            c = a["devs"][j][1]
            op = 1.0 if it.get("hot") else 0.45 if it.get("cold") else 0.75
            if it.get("half"):
                o += rect(x * U, -(y + 2) * U, 9 * U, 9 * U, None, stroke=c) + rect(x * U, -(y + 6.5) * U, 9 * U, 4.5 * U, c, op)
            else:
                o += rect(x * U, -(y + 2) * U, 9 * U, 9 * U, c, op)
            x += 11
    return o


def panel(a, ox, oy):
    """One architecture: rows are layers (L0 at the bottom), columns are devices, and a strip shows who works."""
    nd, pad, rowh, top = len(a["devs"]), 22, 15, 18
    colw = (W - pad - 6) / nd
    o = f"\\begin{{scope}}[shift={{({ox:.3f},{oy:.3f})}}]\n"
    o += text(0, 0.45, a["name"], size="small", bold=True, color="stb" if a.get("ours") else "ink")
    o += text(0, 0.1, a["ex"], size="tiny", color="dim")
    for j, (n, c) in enumerate(a["devs"]):
        o += text((pad + j * colw + 2) * U, -0.2, n, size="tiny", color=c, bold=True)
        o += rect((pad + j * colw) * U, -(top - 2) * U, (colw - 6) * U, (LAYERS * rowh + 2) * U, None, stroke="rule")
    for l in range(LAYERS):
        y = top + (LAYERS - 1 - l) * rowh
        o += text((pad - 4) * U, -(y + 5) * U, f"L{l}", size="tiny", anchor="east", color="dim")
        o += place_items(a, l, y, pad, colw)
    sy, lane, sw = top + LAYERS * rowh + 14, 9, (W - pad - 6) / LAYERS
    o += text(pad * U, -(sy - 4) * U, "who works, one token", size="tiny", color="dim")
    for j, (n, c) in enumerate(a["devs"]):
        o += text((pad - 4) * U, -(sy + 4.5 + j * (lane + 3)) * U, n.split()[0][:4], size="tiny", anchor="east", color=c)
    for l in range(LAYERS):
        x0 = pad + l * sw
        for j, (n, c) in enumerate(a["devs"]):
            o += rect((x0 + 1) * U, -(sy + j * (lane + 3)) * U, (sw - 2) * U, lane * U, "rule", 0.35)
        for j, segs in enumerate(a["work"](l)):
            for s, e in segs:
                op = 0.6 if (j == 2 and a.get("ours")) else 0.95
                o += rect((x0 + 1 + s * (sw - 2)) * U, -(sy + j * (lane + 3)) * U, (e - s) * (sw - 2) * U, lane * U, a["devs"][j][1], op)
        for p in a["ticks"](l):
            x = (x0 + 1 + p * (sw - 2)) * U
            o += f"\\draw[dashed, line width=0.3pt] ({x:.3f},{-(sy - 1) * U:.3f}) -- ({x:.3f},{-(sy + nd * (lane + 3) - 2) * U:.3f});\n"
    ybot = -(sy + nd * (lane + 3) + 6) * U
    o += f"\\node[anchor=north west, inner sep=0pt, text width={(W - pad) * U:.2f}cm, font=\\tiny] at (0,{ybot:.3f}) {{{a['verdict']} \\emph{{{a['vend']}.}}}};\n"
    return o + "\\end{scope}\n"


def fig_archs():
    o = "\\begin{tikzpicture}\n"
    for i, a in enumerate(ARCHS):
        o += panel(a, (i % 2) * 8.1, -(i // 2) * 5.6)
    return o + "\\end{tikzpicture}\n"


if __name__ == "__main__":
    texts = {"fig-weight.tex": fig_weight(), "fig-racks.tex": fig_racks(), "fig-archs.tex": fig_archs()}
    for name, body in texts.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(HEAD + body)
