"""Retire the old add-on name from a tree: ``retire_name.py [--root DIR] [--dry-run]``.

OWNER: this file owns the owner-approved map of 2026-11-21 (the old add-on's identifiers -> the Seabraid/Strata ones; the
RULES table below IS the map).  WHY not scripts/rename.py: that tool maps ONE name to ONE name by casing; this retirement
maps one name to several targets by context (env var, namespace, log prefix, directory, wire tag), so the rules are an ordered
table and "the order matters" is written down once, here.  It reuses rename.py's patch-hunk check (one owner) and
``checks/_common`` for the tracked-file list.  The old name is spelled in halves so the whole-tree name gate does not see it here.
CONTRACT: for every tracked or untracked-not-ignored file under ROOT, rewrite the CONTENT and the PATH by RULES (first rule
that matches a span wins, because each rule runs over the output of the one before it), move files with ``git mv`` when ROOT is a
git tree (``os.replace`` otherwise), and print counts per rule.  Two files that become the same path, a destination that already
exists, or a new identifier that already names something else REFUSE the run before any write.  Re-running finds nothing and
is a no-op, so it is safe to run twice.  A binary is renamed by path only; one that contains the name is reported.
GENERATED FILES: the Strata patch series and the opt-in mbox are NOT edited as text (an edit leaves stale index lines and
file order); they are regenerated by applying the old series to Strata, running THIS script on that checkout, and
``git format-patch``.  A series patch that still names the old tool REFUSES here with that instruction.  ``.patch`` files that
are plain documents are rewritten and their hunk headers re-verified.
USE ON A STRATA CHECKOUT: ``--root STRATA --paths-from LIST`` limits the run to the listed files (the ones the series touches),
``--skip-token-check`` skips the whole-tree identifier scan, and ``--filter`` rewrites stdin to stdout (commit messages, authors).
FAILURE: fail-fast and loud; exit 1 with the reason before any write.  SIZE: <=500 lines.
CHECKER: tests/test_retire_name.py (every rule, the refusals, idempotence) and checks/check_names.py --forbid <old name>.
"""

from __future__ import annotations

import argparse
import fnmatch
import os
import re
import subprocess
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "checks"))
sys.path.insert(0, HERE)
import _common as common  # noqa: E402
import rename  # noqa: E402  (hunk_problems: the one owner of the patch-header check)

OLD = "blam" + "mer"  # WHY halves: the name gate scans every tracked file, this one included
UP, CAP = OLD.upper(), OLD.capitalize()
OLD_TAG = "BLAM" + "MR1"  # the old wire magic text; 7 bytes plus NUL, so "SEABRD1" fills the same u64
OLD_MAGIC_HEX = "31524D4D414C42"  # the same bytes read as a little-endian u64 (0x31 '1' ... 0x42 'B')
NEW_MAGIC_HEX = "31445242414553"  # "SEABRD1" the same way: 31 44 52 42 41 45 53

def _magic_hex(m: re.Match) -> str:
    """The new magic in the casing the old one was written in (the 0x prefix is kept)."""
    body = NEW_MAGIC_HEX.lower() if m.group(0).endswith(OLD_MAGIC_HEX.lower()) else NEW_MAGIC_HEX
    return (m.group(1) or "") + body


# (rule name, pattern, replacement (text, or a function of the match), kinds).  KINDS says where a rule applies, one letter each:
#   p = a file path, c = the content of a code or data file, d = the content of a document (.md, .tex, NOTICE, CITATION.cff).
# WHY the split: in a document the bare uppercase name is prose and reads best as "Strata integration"; in code it is a log,
# error or comment word and must read as the new product word "seabraid" (the engine's log text is produced by code, and a
# document that quotes it must quote what the code now prints, so the runtime-message rule gives both the same lowercase word).
# ORDER MATTERS, top to bottom, each rule sees the previous rule's output:
#  - the macro and the person lines go first because a later, more general rule would split them;
#  - the env rule (UP_) goes before every bare-UP rule so SHM, HOT_SHARE ... become SEABRAID_STRATA_*, never the bare name;
#  - "compat/<old>" goes before the generic lowercase rule so the directory becomes compat/strata, not compat/seabraid;
#  - the bare-UP rules (prose, code-bare) come after every UP form that has a meaning of its own;
#  - helper-begin-finish goes before the generic lowercase rule: the map says seabraid_*, but RemoteExperts already has
#    seabraid_begin and seabraid_finish (the private Qwen tier) with the same arguments, so the helper-channel pair becomes
#    seabraid_helper_begin / seabraid_helper_finish instead of two functions of one name (a deviation from the map);
#  - binary-dir goes before the generic lowercase rule: Strata's CMake adds the add-on's strata-ext and, from v7, the Seabraid
#    source as subdirectories with a build directory each, and both would be called seabraid (CMake refuses that), so the
#    add-on's one becomes seabraid-strata-ext (the second deviation from the map).
_SAID = r"(?:helper|retier|channel|private|phase|is serving|engine mismatch|geometry mismatch)"
RULES: tuple[tuple, ...] = (
    ("retier-macro", rf"STRATA_HAVE_{UP}_RETIER", "STRATA_HAVE_SEABRAID_RETIER", "pcd"),
    ("magic-hex", rf"(?i)(0x)?{OLD_MAGIC_HEX}", _magic_hex, "cd"),
    ("magic-text", OLD_TAG, "SEABRD1", "pcd"),
    ("author", rf"{UP} <{OLD}@", "Seabraid <seabraid@", "cd"),
    ("env", rf"{UP}_", "SEABRAID_STRATA_", "pcd"),
    ("bench-marker", rf"{UP}-(?=[A-Z])", "SEABRAID-", "pcd"),
    ("lower-dash", rf"{UP}-(?=[a-z])", "seabraid-", "pcd"),
    ("log-prefix", rf"{UP}:", "seabraid:", "pcd"),
    ("compat-dir", rf"(compat(?:[/.]|[\"'] ?[,/] ?[\"'])){OLD}", r"\1strata", "pcd"),   # also Path("compat") / "<old>" and ("compat", "<old>")
    ("add-on", rf"{UP} add-on", "Strata integration", "cd"),
    ("runtime-message", rf"{UP}(?= {_SAID}\b)", "seabraid", "cd"),
    ("prose", UP, "Strata integration", "d"),
    ("code-bare", UP, "seabraid", "cp"),
    ("binary-dir", rf"(?<=CMAKE_BINARY_DIR\}}/){OLD}\b", "seabraid-strata-ext", "pcd"),
    ("helper-begin-finish", rf"{OLD}_(begin|finish)\b", r"seabraid_helper_\1", "pcd"),
    ("capitalised", CAP, "Seabraid", "pcd"),
    ("lower", OLD, "seabraid", "pcd"),
)
_COMPILED = tuple((n, re.compile(p), r, k) for n, p, r, k in RULES)
DOC_SUFFIXES = (".md", ".tex")
DOC_NAMES = frozenset({"NOTICE", "CITATION.cff"})

# WHY a glob list: these two kinds of file are produced by `git format-patch`, never by a text edit (see the module docstring).
GENERATED = ("compat/*/patches/strata/0*.patch", "adapters/strata/strata-v7-seabraid.patch")
# WHY exempt: they name the old project as their INPUT, so rewriting them would break the next run.
SELF_EXEMPT = frozenset({"scripts/retire_name.py", "tests/test_retire_name.py"})
# WHY a table with a reason per row: an identifier that collides after the rename is refused unless a human has said why the
# two live in different scopes.
TOKEN_ALLOW: dict[str, str] = {
    "Seabraid": "a bare capitalised name in code is a word in a comment or a message, not an identifier",
    "seabraid_": "a prefix in front of a CMake variable reference (name_${x}), not a whole identifier",
    "seabraid_open": "RemoteExperts::seabraid_open (a class member in the Strata tree) and the C ABI's free function seabraid_open are different "
                     "scopes; the Strata build compiles both and is the checker",
    "kSeabraid": "spawn_policy.cpp's kSeabraid array (an anonymous-namespace constant) and RetierPromote::kSeabraid (an enumerator) never share a scope",
    "seabraid": "the map turns the C++ namespace into seabraid, which joins the adapter's existing namespace seabraid::strata_adapter; "
                "a member that clashes fails to compile, so the build is the checker",
}
WORD = re.compile(r"[A-Za-z0-9_]+")


class RetireError(Exception):
    """A refusal the user can act on; raised before anything is written."""


def kind_of(rel: str) -> str:
    """The kind of content in a file: d for a document, c for any other file (see rewrite())."""
    return "d" if rel.endswith(DOC_SUFFIXES) or os.path.basename(rel) in DOC_NAMES else "c"


def rewrite(text: str, kind: str = "c") -> tuple[str, Counter]:
    """Apply RULES in order for one kind ("p" path, "c" code content, "d" document content).  Returns (new text, count per rule)."""
    counts: Counter = Counter()
    for name, rx, repl, kinds in _COMPILED:
        if kind not in kinds:
            continue
        text, n = rx.subn(repl, text)
        if n:
            counts[name] += n
    return text, counts


def has_old_name(data: str) -> bool:
    return OLD in data.lower() or OLD_TAG.lower() in data.lower() or OLD_MAGIC_HEX.lower() in data.lower()


def is_generated(rel: str) -> bool:
    return any(fnmatch.fnmatch(rel, g) for g in GENERATED)


def read_file(root: str, rel: str) -> tuple[bytes, str | None]:
    """(raw bytes, text or None when binary).  WHY surrogateescape: a byte-exact round trip, CRLF and odd bytes included."""
    with open(os.path.join(root, rel), "rb") as fh:
        raw = fh.read()
    if b"\0" in raw[:8192]:
        return raw, None
    return raw, raw.decode("utf-8", "surrogateescape")


def plan_file(root: str, rel: str) -> dict | None:
    """What to do with one file: {rel, dest, data (bytes or None), counts, warning}, or None when nothing changes."""
    raw, text = read_file(root, rel)
    dest, path_counts = rewrite(rel, "p")
    out, counts, warning = None, Counter(path_counts), None
    if text is None:
        warning = f"{rel}: binary file contains the old name; not rewritten" if has_old_name(raw.decode("latin-1")) else None
    elif is_generated(rel) and has_old_name(text):
        raise RetireError(f"{rel}: a generated patch still names the old tool; regenerate it from Strata (git am, this script on the checkout, git format-patch), do not edit it")
    elif rel not in SELF_EXEMPT:
        new_text, text_counts = rewrite(text, kind_of(rel))
        counts += text_counts
        out = new_text.encode("utf-8", "surrogateescape") if new_text != text else None
        check_patch_hunks(rel, text, new_text)
    if out is None and dest == rel:
        return None
    return {"rel": rel, "dest": dest, "data": out, "counts": counts, "warning": warning}


def check_patch_hunks(rel: str, before: str, after: str) -> None:
    """A document patch whose hunk line counts became wrong because of the rewrite is refused (a pre-existing fault is not ours)."""
    if rel.endswith(".patch") and before != after and len(rename.hunk_problems(after)) > len(rename.hunk_problems(before)):
        raise RetireError(f"{rel}: patch hunks inconsistent after the rewrite ({rename.hunk_problems(after)[0]}); refusing")


def plan_paths(plans: list[dict]) -> None:
    """Refuse two sources with one destination, and a destination that exists and is not itself moving away."""
    seen: dict[str, str] = {}
    for p in plans:
        if p["dest"] in seen:
            raise RetireError(f"collision: {p['rel']} and {seen[p['dest']]} both become {p['dest']}")
        seen[p["dest"]] = p["rel"]


def refuse_overwrites(root: str, plans: list[dict], all_files: set[str]) -> None:
    moving = {p["rel"] for p in plans if p["dest"] != p["rel"]}
    for p in plans:
        if p["dest"] != p["rel"] and p["dest"] in all_files and p["dest"] not in moving:
            raise RetireError(f"collision: {p['rel']} -> {p['dest']} would overwrite an existing tracked file")
        if p["dest"] != p["rel"] and p["dest"] not in moving and os.path.exists(os.path.join(root, p["dest"])):
            raise RetireError(f"collision: {p['rel']} -> {p['dest']} would overwrite an existing file")


def code_tokens(root: str, files: list[str]) -> tuple[set[str], set[str]]:
    """(tokens that carry the old name, every other token) over the source files.

    WHY source files only and not the generated patches: documents repeat names without defining them, and the regenerated
    patches already carry the new names, so counting either would flag every token as its own collision."""
    old_tokens: set[str] = set()
    other: set[str] = set()
    for rel in files:
        if rel in SELF_EXEMPT or is_generated(rel) or not common.is_source(rel):
            continue
        _, text = read_file(root, rel)
        for tok in set(WORD.findall(text or "")):
            (old_tokens if has_old_name(tok) else other).add(tok)
    return old_tokens, other


def token_collisions(root: str, files: list[str]) -> list[str]:
    """New identifiers that already exist untouched elsewhere in the code (two things would share one name after the rename)."""
    old_tokens, other = code_tokens(root, files)
    out = []
    for tok in sorted(old_tokens):
        new = rewrite(tok, "c")[0]
        if new in other and new not in TOKEN_ALLOW:
            out.append(f"identifier collision: {tok} -> {new}, which already exists in the tree")
    return out


def list_files(root: str, paths_from: str | None) -> list[str]:
    files = common.tracked(root)
    if paths_from is None:
        return files
    with open(paths_from, encoding="utf-8") as fh:
        wanted = {ln.strip() for ln in fh if ln.strip()}
    missing = wanted - set(files)
    if missing:
        raise RetireError(f"--paths-from lists files that are not in the tree: {sorted(missing)[:3]}")
    return [f for f in files if f in wanted]


def build_plan(root: str, paths_from: str | None, token_check: bool) -> dict:
    files = list_files(root, paths_from)
    plans = [p for p in (plan_file(root, rel) for rel in files) if p]
    plan_paths(plans)
    refuse_overwrites(root, plans, set(common.tracked(root)))
    problems = token_collisions(root, files) if token_check else []
    if problems:
        raise RetireError("; ".join(problems[:10]) + (f" (+{len(problems) - 10} more)" if len(problems) > 10 else ""))
    return {"plans": plans, "warnings": [p["warning"] for p in plans if p["warning"]]}


def in_git(root: str) -> bool:
    return os.path.exists(os.path.join(root, ".git"))


def move_file(root: str, rel: str, dest: str) -> None:
    os.makedirs(os.path.dirname(os.path.join(root, dest)) or root, exist_ok=True)
    if in_git(root):
        subprocess.run(["git", "-C", root, "mv", "-k", "--", rel, dest], check=True, capture_output=True)
        if os.path.exists(os.path.join(root, rel)):  # `-k` skips an untracked source silently; fall back to a plain move
            os.replace(os.path.join(root, rel), os.path.join(root, dest))
    else:
        os.replace(os.path.join(root, rel), os.path.join(root, dest))


def prune_empty(root: str, rel: str) -> None:
    parent = os.path.dirname(os.path.join(root, rel))
    while parent != root and os.path.isdir(parent) and not os.listdir(parent):
        os.rmdir(parent)
        parent = os.path.dirname(parent)


def apply_plan(root: str, plan: dict) -> None:
    for p in plan["plans"]:
        if p["data"] is not None:
            with open(os.path.join(root, p["rel"]), "wb") as fh:
                fh.write(p["data"])
    for p in plan["plans"]:
        if p["dest"] != p["rel"]:
            move_file(root, p["rel"], p["dest"])
            prune_empty(root, p["rel"])


def report(plan: dict, dry: bool) -> None:
    total: Counter = Counter()
    moved = 0
    for p in plan["plans"]:
        total += p["counts"]
        moved += p["dest"] != p["rel"]
    for rule, n in sorted(total.items()):
        print(f"{n:6d}  {rule}")
    for w in plan["warnings"]:
        print("warning: " + w)
    print(f"retire_name: {'DRY RUN, nothing written: ' if dry else ''}{sum(total.values())} replacement(s) in "
          f"{sum(1 for p in plan['plans'] if p['data'] is not None)} file(s), {moved} path(s) moved, {len(plan['plans'])} file(s) touched")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--root", default=common.default_root())
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--paths-from", help="a file listing the only paths to consider (a Strata checkout: the files the series touches)")
    ap.add_argument("--skip-token-check", action="store_true", help="skip the whole-tree identifier collision scan")
    ap.add_argument("--filter", action="store_true", help="rewrite stdin to stdout with the text rules and exit (commit messages)")
    a = ap.parse_args(argv)
    if a.filter:
        sys.stdout.write(rewrite(sys.stdin.read())[0])
        return 0
    root = os.path.abspath(a.root)
    try:
        plan = build_plan(root, a.paths_from, not a.skip_token_check)
        if not a.dry_run:
            apply_plan(root, plan)
    except (RetireError, subprocess.CalledProcessError) as exc:
        print(f"retire_name: REFUSED: {exc}", file=sys.stderr)
        return 1
    report(plan, a.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
